import "server-only";
import type { DatasetEntry } from "@/types/registry";
import { getGeoBuildInfo } from "./geo";

/*
 * The dataset registry as the site renders it on /methodology#sources (D-051).
 * `data/PROVENANCE.md` is the full human-readable registry; a unit test keeps the two in step,
 * and the checksums and retrieval date come from what the geodata build actually read.
 */

